import { readdir, readFile, writeFile } from 'node:fs/promises';

// Use the same static, type-checked catalog in Vite, Node tests and offline builds.
const root = new URL('../src/assets/packs/', import.meta.url);
const files = (await readdir(root)).filter(file => file.endsWith('.pack.json')).sort();
const packs = [];
const ids = new Set();
for (const file of files) {
  try {
    const source = JSON.parse(await readFile(new URL(file, root), 'utf8'));
    if (typeof source.id !== 'string' || !/^[a-z][a-z0-9_-]*:[a-z][a-z0-9_-]*$/.test(source.id) ||
        ids.has(source.id) || source.schemaVersion !== 1)
      throw new Error('ID duplicado, ausente ou versão incompatível');
    ids.add(source.id);
    packs.push({ file, source });
  } catch (error) {
    throw new Error(file + ': ' + error.message);
  }
}
const target = new URL('./generated.ts', root);
const ordered = [];
const resolved = new Set();
const visiting = new Set();
const byId = new Map(packs.map(pack => [pack.source.id, pack]));
function resolve({ file, source }) {
  if (resolved.has(source.id)) return;
  if (visiting.has(source.id)) throw new Error(file + ': dependência circular');
  visiting.add(source.id);
  for (const id of source.dependencies ?? []) {
    if (!byId.has(id)) throw new Error(file + ': pacote ausente ' + id);
    resolve(byId.get(id));
  }
  visiting.delete(source.id);
  resolved.add(source.id);
  ordered.push('// ' + file + '\n' + JSON.stringify(source));
}
packs.forEach(resolve);
const code = "// Generated by tools/index-content.mjs\nimport type { ContentPack } from '../../business/content/ContentPack';\nexport const packs: ContentPack[] = [\n" + ordered.join(',\n') + '\n];\n';
if ((await readFile(target, 'utf8').catch(() => '')) !== code) await writeFile(target, code);
